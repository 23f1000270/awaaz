"""Write the trained weights as a C header (firmware) and JSON (browser demo).

    python train/export.py awaaz/weights.npz
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def c_array(name: str, a: np.ndarray) -> str:
    vals = ",".join(f"{v:.9g}f" for v in a.astype(np.float32).ravel())
    return f"static const float {name}[{a.size}] = {{{vals}}};\n"


def main(path: str) -> None:
    w = dict(np.load(path))
    res = ROOT / "eval" / "results" / "results.json"
    thr = json.loads(res.read_text())["threshold"] if res.exists() else 0.5
    header = ["/* Generated by train/export.py from the trained model. Do not edit. */\n",
              "#ifndef AWAAZ_WEIGHTS_H\n#define AWAAZ_WEIGHTS_H\n",
              f"#define AWZ_THRESHOLD {thr:.2f}f  /* chosen on the validation split, see eval/evaluate.py */\n"]
    for k in sorted(w):
        header.append(c_array(k, w[k]))
    header.append("#endif\n")
    (ROOT / "csrc" / "awaaz_weights.h").write_text("".join(header))
    (ROOT / "site" / "weights.json").write_text(json.dumps(
        {"threshold": thr, **{k: {"shape": list(v.shape), "data": [float(x) for x in v.ravel()]} for k, v in w.items()}},
        separators=(",", ":")))
    print("wrote csrc/awaaz_weights.h and site/weights.json")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "awaaz" / "weights.npz"))
